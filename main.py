def generar_pdf_orden(p):
    pdf = FPDF()
    pdf.add_page()
    pdf.set_font('Arial', 'B', 14)
    pdf.cell(0, 10, 'CCU SANTA FE - Orden de Pedido de Materiales', 0, 1, 'C')
    pdf.set_font('Arial', 'I', 9)
    pdf.cell(0, 6, f"Fecha de emisión: {datetime.now().strftime('%d/%m/%Y %H:%M')}", 0, 1, 'C')
    pdf.ln(5)

    pdf.set_font('Arial', 'B', 11)
    pdf.cell(0, 7, f"Pedido #{p['id']} | Solicitante: {p['usuario']} | Fecha: {p['fecha']}", 0, 1)
    pdf.set_font('Arial', '', 10)
    pdf.cell(0, 6, f"Estado: {p['estado']}", 0, 1)
    pdf.ln(4)

    pdf.set_font('Arial', 'B', 10)
    pdf.cell(0, 6, 'Detalle de Materiales Solicitados:', 0, 1)
    pdf.set_font('Arial', '', 10)

    for mat, cant in p['items'].items():
        rec = p.get('recibidos', {}).get(mat, 0)
        pend = p.get('pendientes', {}).get(mat, cant)
        pdf.cell(0, 6, f'- {mat}  ->  Pedido: {cant}  (Llegó: {rec} | Pendiente: {pend})', 0, 1)

    filename = f"Pedido_CCU_{p['id']}_{datetime.now().strftime('%Y%m%d_%H%M%S')}.pdf"
    pdf.output(filename)
    return filename


def main(page: ft.Page):
    page.title = 'Pedido de Materiales - CCU Santa Fe'
    page.theme_mode = ft.ThemeMode.LIGHT
    page.padding = 0
    page.bgcolor = ft.colors.WHITE

    es_autorizador = False
    usuario_actual = 'Operario'
    carrito = {}
    tab_actual = 'materiales'

    badge_text = ft.Text('0', color=ft.colors.WHITE, size=12, weight=ft.FontWeight.BOLD)
    badge_container = ft.Container(
        content=badge_text,
        bgcolor='#1E293B',
        border_radius=10,
        padding=ft.padding.symmetric(horizontal=8, vertical=2),
        visible=False,
    )

    badge_pendientes = ft.Text('0', color=ft.colors.WHITE, size=12, weight=ft.FontWeight.BOLD)
    badge_pend_container = ft.Container(
        content=badge_pendientes,
        bgcolor='#DC2626',
        border_radius=10,
        padding=ft.padding.symmetric(horizontal=8, vertical=2),
        visible=False,
    )

    btn_tab_mat = ft.ElevatedButton('Materiales', expand=True)
    btn_tab_ped = ft.OutlinedButton(
        content=ft.Row([ft.Text('Mi pedido'), badge_container], alignment=ft.MainAxisAlignment.CENTER, spacing=5),
        expand=True,
    )
    btn_tab_aprob = ft.OutlinedButton(
        content=ft.Row([ft.Text('Gestión / Autorizar'), badge_pend_container], alignment=ft.MainAxisAlignment.CENTER, spacing=5),
        expand=True,
        visible=es_autorizador,
    )
    btn_tab_rep = ft.OutlinedButton('Reportes Históricos', expand=True, visible=es_autorizador)

    txt_busqueda = ft.TextField(
        hint_text='Buscar material...',
        prefix_icon=ft.icons.SEARCH,
        border_radius=10,
        bgcolor=ft.colors.GREY_100,
    )

    lista_materiales_view = ft.ListView(expand=True, spacing=10)
    lista_pedido_view = ft.ListView(expand=True, spacing=10)
    lista_aprobaciones_view = ft.ListView(expand=True, spacing=10)
    lista_reportes_view = ft.ListView(expand=True, spacing=10)

    lbl_resumen_items = ft.Text('0 items seleccionados', size=14, color=ft.colors.GREY_700)
    btn_enviar_pedido = ft.ElevatedButton(
        'Enviar Pedido',
        icon=ft.icons.SEND,
        bgcolor='#0F2942',
        color=ft.colors.WHITE,
        disabled=True,
    )

    def actualizar_badges():
        total_items = sum(carrito.values())
        if total_items > 0:
            badge_text.value = str(total_items)
            badge_container.visible = True
            lbl_resumen_items.value = f'{total_items} items seleccionados'
            btn_enviar_pedido.disabled = False
        else:
            badge_container.visible = False
            lbl_resumen_items.value = '0 items seleccionados'
            btn_enviar_pedido.disabled = True

        pendientes = sum(1 for p in PEDIDOS_DB if p['estado'] == 'Pendiente')
        if pendientes > 0 and es_autorizador:
            badge_pendientes.value = str(pendientes)
            badge_pend_container.visible = True
        else:
            badge_pend_container.visible = False
        page.update()

    def render_materiales(filtro=''):
        lista_materiales_view.controls.clear()
        for mat in MATERIALES_BASE:
            if filtro.lower() in mat.lower():
                cant = carrito.get(mat, 0)

                def make_add(m=mat):
                    def handler(e):
                        carrito[m] = carrito.get(m, 0) + 1
                        render_materiales(txt_busqueda.value or '')
                        actualizar_badges()
                    return handler

                def make_remove(m=mat):
                    def handler(e):
                        if m in carrito:
                            carrito[m] -= 1
                            if carrito[m] <= 0:
                                del carrito[m]
                            render_materiales(txt_busqueda.value or '')
                            actualizar_badges()
                    return handler

                card = ft.Card(
                    content=ft.Container(
                        padding=10,
                        content=ft.Row([
                            ft.Text(mat, expand=True, weight=ft.FontWeight.W_500, size=13),
                            ft.Row(
                                [
                                    ft.IconButton(
                                        ft.icons.REMOVE_CIRCLE_OUTLINE,
                                        on_click=make_remove(),
                                        icon_color=ft.colors.RED_400 if cant > 0 else ft.colors.GREY_400,
                                    ),
                                    ft.Text(str(cant), weight=ft.FontWeight.BOLD, size=15),
                                    ft.IconButton(
                                        ft.icons.ADD_CIRCLE_OUTLINE,
                                        on_click=make_add(),
                                        icon_color=ft.colors.GREEN_600,
                                    ),
                                ],
                                alignment=ft.MainAxisAlignment.END,
                            ),
                        ]),
                    )
                )
                lista_materiales_view.controls.append(card)
        page.update()

    def render_pedido():
        lista_pedido_view.controls.clear()
        if not carrito:
            lista_pedido_view.controls.append(
                ft.Container(
                    content=ft.Text('El pedido está vacío', color=ft.colors.GREY_500, size=16),
                    alignment=ft.alignment.center,
                    padding=20,
                )
            )
        else:
            for mat, cant in carrito.items():
                card = ft.Card(
                    content=ft.Container(
                        padding=10,
                        content=ft.Row([
                            ft.Text(mat, expand=True, size=13),
                            ft.Text(f'Cant: {cant}', weight=ft.FontWeight.BOLD, size=14),
                        ]),
                    )
                )
                lista_pedido_view.controls.append(card)
        page.update()

    def render_aprobaciones():
        lista_aprobaciones_view.controls.clear()
        pendientes = [p for p in PEDIDOS_DB if p['estado'] == 'Pendiente']
        if not pendientes:
            lista_aprobaciones_view.controls.append(
                ft.Container(
                    content=ft.Text('No hay pedidos pendientes de autorización', color=ft.colors.GREY_500, size=14),
                    alignment=ft.alignment.center,
                    padding=20,
                )
            )
        else:
            for p in pendientes:
                items_str = ', '.join([f'{mat} (x{cant})' for mat, cant in p['items'].items()])

                def aprobar_click(pid=p['id']):
                    for item in PEDIDOS_DB:
                        if item['id'] == pid:
                            item['estado'] = 'Aprobado / Pendiente de Entrega'
                            item['pendientes'] = dict(item['items'])
                            item['recibidos'] = {k: 0 for k in item['items']}
                    render_aprobaciones()
                    actualizar_badges()

                def rechazar_click(pid=p['id']):
                    for item in PEDIDOS_DB:
                        if item['id'] == pid:
                            item['estado'] = 'Rechazado'
                    render_aprobaciones()
                    actualizar_badges()

                def imprimir_click(p_item=p):
                    try:
                        fname = generar_pdf_orden(p_item)
                        page.snack_bar = ft.SnackBar(ft.Text(f'¡PDF del pedido generado: {fname}!'))
                    except Exception as ex:
                        page.snack_bar = ft.SnackBar(ft.Text(f'Error al generar PDF: {ex}'))
                    page.snack_bar.open = True
                    page.update()

                card = ft.Card(
                    content=ft.Container(
                        padding=12,
                        content=ft.Column([
                            ft.Row(
                                [
                                    ft.Text(f"Solicitante: {p['usuario']}", weight=ft.FontWeight.BOLD),
                                    ft.Text(p['fecha'], size=11, color=ft.colors.GREY_600),
                                ],
                                alignment=ft.MainAxisAlignment.SPACE_BETWEEN,
                            ),
                            ft.Text(f'Materiales: {items_str}', size=12),
                            ft.Row(
                                [
                                    ft.ElevatedButton(
                                        '🖨️ Imprimir PDF',
                                        bgcolor='#1E293B',
                                        color=ft.colors.WHITE,
                                        on_click=lambda e, pi=p: imprimir_click(pi),
                                    ),
                                    ft.ElevatedButton(
                                        'Rechazar',
                                        bgcolor=ft.colors.RED_600,
                                        color=ft.colors.WHITE,
                                        on_click=lambda e, pid=p['id']: rechazar_click(pid),
                                    ),
                                    ft.ElevatedButton(
                                        'Aprobar',
                                        bgcolor=ft.colors.GREEN_600,
                                        color=ft.colors.WHITE,
                                        on_click=lambda e, pid=p['id']: aprobar_click(pid),
                                    ),
                                ],
                                alignment=ft.MainAxisAlignment.END,
                                spacing=10,
                            ),
                        ]),
                    )
                )
                lista_aprobaciones_view.controls.append(card)
        page.update()

    def eliminar_pedido_historico(pid):
        global PEDIDOS_DB
        PEDIDOS_DB = [p for p in PEDIDOS_DB if p['id'] != pid]
        render_reportes()
        render_aprobaciones()
        actualizar_badges()
        page.snack_bar = ft.SnackBar(ft.Text("Pedido eliminado del historial."))
        page.snack_bar.open = True
        page.update()

    def render_reportes():
        lista_reportes_view.controls.clear()
        if not PEDIDOS_DB:
            lista_reportes_view.controls.append(
                ft.Container(
                    content=ft.Text('No hay registros históricos', color=ft.colors.GREY_500, size=14),
                    alignment=ft.alignment.center,
                    padding=20,
                )
            )
        else:
            for p in PEDIDOS_DB:
                items_det = []
                subtitle_text = ft.Text(f"Fecha: {p['fecha']} | Estado: {p['estado']}", size=12, color=ft.colors.BLUE_800)

                for mat, cant in p['items'].items():
                    rec = p.get('recibidos', {}).get(mat, 0)
                    pend = p.get('pendientes', {}).get(mat, cant)
                    is_checked = (rec == cant and cant > 0)

                    txt_info = ft.Text(f"Llegó: {rec} | Pend: {pend}", size=11, color=ft.colors.GREY_700)

                    def make_check_handler(m_name=mat, t_info=txt_info, sub_ref=subtitle_text, p_obj=p):
                        def handler(e):
                            cant_total = p_obj['items'][m_name]
                            rec_val = cant_total if e.control.value else 0
                            if 'recibidos' not in p_obj:
                                p_obj['recibidos'] = {}
                            if 'pendientes' not in p_obj:
                                p_obj['pendientes'] = {}
                            p_obj['recibidos'][m_name] = rec_val
                            p_obj['pendientes'][m_name] = cant_total - rec_val
                            
                            t_info.value = f"Llegó: {rec_val} | Pend: {cant_total - rec_val}"
                            
                            todos_listos = all(p_obj.get('recibidos', {}).get(m, 0) == p_obj['items'][m] for m in p_obj['items'])
                            if todos_listos:
                                p_obj['estado'] = 'Completado'
                            else:
                                p_obj['estado'] = 'Aprobado / Pendiente de Entrega'
                                
                            sub_ref.value = f"Fecha: {p_obj['fecha']} | Estado: {p_obj['estado']}"
                            actualizar_badges()
                            page.update()
                        return handler

                    items_det.append(
                        ft.Row([
                            ft.Checkbox(
                                label=f"{mat} (Pedido: {cant})",
                                value=is_checked,
                                on_change=make_check_handler(),
                                expand=True
                            ),
                            txt_info
                        ], alignment=ft.MainAxisAlignment.SPACE_BETWEEN)
                    )

                def imprimir_rep_click(p_item=p):
                    try:
                        fname = generar_pdf_orden(p_item)
                        page.snack_bar = ft.SnackBar(ft.Text(f'¡PDF del pedido generado: {fname}!'))
                    except Exception as ex:
                        page.snack_bar = ft.SnackBar(ft.Text(f'Error al generar PDF: {ex}'))
                    page.snack_bar.open = True
                    page.update()

                expansion_tile = ft.ExpansionTile(
                    title=ft.Text(f"Pedido #{p['id']} - {p['usuario']}", weight=ft.FontWeight.BOLD),
                    subtitle=subtitle_text,
                    trailing=ft.IconButton(
                        icon=ft.icons.DELETE_OUTLINE,
                        icon_color=ft.colors.RED_400,
                        tooltip="Borrar pedido erróneo",
                        on_click=lambda e, pid=p['id']: eliminar_pedido_historico(pid)
                    ),
                    controls=[
                        ft.Container(
                            content=ft.Column([
                                ft.Divider(),
                                *items_det,
                                ft.Row(
                                    [
                                        ft.ElevatedButton(
                                            '🖨️ Imprimir Pedido en PDF',
                                            bgcolor='#1E293B',
                                            color=ft.colors.WHITE,
                                            on_click=lambda e, pi=p: imprimir_rep_click(pi),
                                        )
                                    ],
                                    alignment=ft.MainAxisAlignment.END,
                                ),
                            ]),
                            padding=10
                        )
                    ]
                )

                card = ft.Card(content=expansion_tile)
                lista_reportes_view.controls.append(card)
        page.update()

